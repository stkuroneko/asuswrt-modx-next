int is_envram_empty(const char *name)
{
	int ret = 0;
	char cmd[64], buf[512];
	FILE *pfp = NULL;

	if(!name)
		return 1;

	sprintf(cmd, "envram get %s", name);
	pfp = popen(cmd, "r");
	if(pfp != NULL){
		memset(buf, 0, sizeof(buf));
		fgets(buf, sizeof(buf), pfp);
		if(!buf[0]) { 
			ret = 1;
			_dprintf("%s: envram %s is empty.\n", __func__, name);
		}
		pclose(pfp);
	} else
		_dprintf("popen fail.");
 
	return ret;
}

