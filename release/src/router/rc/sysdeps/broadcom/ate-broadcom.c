void asus_ctrl_enband5grp() {

    	char nv_5G[32] = {0};
	char nv_5G2[32] = {0};
    	int dis_ch_grp_5G = 0;
	int dis_ch_grp_5G2 = 0;

	switch( get_model() ) {
		case MODEL_RTAC88U:
		    	snprintf(nv_5G, sizeof(nv_5G), "1:disband5grp");
			break;
		case MODEL_RTAX58U:
			snprintf(nv_5G, sizeof(nv_5G), "1:dis_ch_grp");
			break;
		default:
			return;
	}

	// check current channel group
	if(strlen(nvram_safe_get(nv_5G)) > 0)
		dis_ch_grp_5G = nvram_get_hex(nv_5G);
	else
		dis_ch_grp_5G = 0;

	if(num_of_wl_if() > 2) {
	    	if(strlen(nvram_safe_get(nv_5G2)) > 0)
			dis_ch_grp_5G2 = nvram_get_hex(nv_5G2);
		else
		    	dis_ch_grp_5G2 = 0;
	}

#if defined(RTCONFIG_BCM_7114) || defined(HND_ROUTER)
	// enable 5G band2 if necessary
	if (asus_ctrl_en(ASUSCTRL_DFS_BAND2)) { 
		if((dis_ch_grp_5G & 1<<BIT_CHGRP_2A) ||
		   (dis_ch_grp_5G & 1<<BIT_CHGRP_2B)) {
			if(dis_ch_grp_5G & 1<<BIT_CHGRP_2A)
				dis_ch_grp_5G = (dis_ch_grp_5G & ~(1<<BIT_CHGRP_2A));
			if(dis_ch_grp_5G & 1<<BIT_CHGRP_2B)
				dis_ch_grp_5G = (dis_ch_grp_5G & ~(1<<BIT_CHGRP_2B));
			nvram_set_hex(nv_5G, dis_ch_grp_5G);
		}
	}

	// enable 5G band3 if necessary
	if (asus_ctrl_en(ASUSCTRL_DFS_BAND3)) {
		if(num_of_wl_if() > 2) {
		    	if ((dis_ch_grp_5G2 & 1<<BIT_CHGRP_3)) {
				dis_ch_grp_5G2 = (dis_ch_grp_5G2 & ~(1<<BIT_CHGRP_3));
				nvram_set_hex(nv_5G2, dis_ch_grp_5G2);
			}
		}
		else {
			if ((dis_ch_grp_5G & 1<<BIT_CHGRP_3)) {
				dis_ch_grp_5G = (dis_ch_grp_5G & ~(1<<BIT_CHGRP_3));
				nvram_set_hex(nv_5G, dis_ch_grp_5G);
			}
		}
	}
#endif

}

