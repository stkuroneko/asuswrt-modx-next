void  pcie_probe_check() {
	FILE *procp;
	char line[256], bus[32], vendev[32], irq[32];
	int prb_cnt = 0, reboot_cnt = 0;

	if ((procp = fopen("/proc/bus/pci/devices", "r")) != NULL) {
		while (fgets(line, sizeof(line), procp)) {
			if (sscanf(line, "%s %s %s", bus, vendev, irq) != 3)
				continue;
			if(!strncmp(vendev, DEVID, 8)) {
				_dprintf("[PCIE PROBE CHECK] %s-%s-%s\n", bus, vendev, irq);
				prb_cnt++;
			}
		}
		fclose(procp);
	}

	if(prb_cnt != PRBCNT) {
		reboot_cnt = nvram_get_int("pcieprb_retry");
		if(reboot_cnt < PCIE_REBOOT_RETRY) {
			nvram_set_int("pcieprb_retry", ++reboot_cnt);
			nvram_commit();
			_dprintf("\n\n[PCIE PROBE CHECK] REBOOT ... %d\n\n", reboot_cnt);
			kill(1, SIGTERM);
		}
		else {
			if (!strlen(cfe_nvram_safe_get_raw("pcie_down"))) {
				if (!pids("envrams")) {
					system("/usr/sbin/envrams");
					usleep(100000);
				}
				eval("envram", "set", "pcie_down=1");
				eval("envram", "commit");
				sync(); sync(); sync();
			}
		}
	}
	else {
	    nvram_set_int("pcieprb_retry", 0);
	    nvram_commit();
	}
}
