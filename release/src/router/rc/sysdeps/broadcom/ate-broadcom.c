static char cfebuf_g[CFEBUF_LEN];
char *cfe_nvram_safe_get(const char *name);

int init_cfe_nvram()
{
	FILE *fp = NULL;
	int count, lock;

#if defined(RTCONFIG_CFEZ) && defined(RTCONFIG_BCMARM)
	char *cfez_buf;
	long size;
	int i;
	int ret = -1;

	if (!pids("envrams")) {
		system("/usr/sbin/envrams >/dev/null");
		usleep(100000);
	}

	system("envram show &> /tmp/cfez_nvram");

	if ((fp = fopen("/tmp/cfez_nvram", "rb")) == NULL)
		return ret;

	fseek(fp, 0L, SEEK_END);
	size = ftell(fp);
	fseek(fp, 0L, SEEK_SET);

	cfez_buf = malloc(sizeof(char) * size);
	if (cfez_buf == NULL)
		goto error;

	memset(cfez_buf, 0 , size);
	count = fread(cfez_buf, 1, size, fp);
	if (count != size)
		goto error;

	if (strstr(cfez_buf, "connect failed:") != NULL)
		goto error;

	for(i=0; i<count; i++) {
		if (cfez_buf[i] == '\r' || cfez_buf[i] == '\n')
			cfez_buf[i] = '\0';
	}

	lock = file_lock("cfez_buf");
	memcpy(cfebuf_g, NVRAM_MAGIC_ASCII, strlen(NVRAM_MAGIC_ASCII));
	memcpy(cfebuf_g + strlen(NVRAM_MAGIC_ASCII), cfez_buf, count);
	file_unlock(lock);

	ret = 0;

error:
	if (fp) fclose(fp);
	if (cfez_buf) free(cfez_buf);

	eval("rm", "-f", "/tmp/cfez_nvram");

	return ret;
#else
	char cfebuf[CFEBUF_LEN];

	if ((fp = fopen("/dev/mtd0", "rb")) == NULL)
		return -1;

	if (fseek(fp, 0x400 + sizeof(struct nvram_header), SEEK_SET) < 0)
		return -1;

	memset(cfebuf, 0, CFEBUF_LEN);
	count = fread(cfebuf, 1, CFEBUF_LEN - sizeof(struct nvram_header), fp);
	if (count != (CFEBUF_LEN - sizeof(struct nvram_header)))
		return -1;

	lock = file_lock("cfebuf");

	memcpy(cfebuf_g, NVRAM_MAGIC_ASCII, strlen(NVRAM_MAGIC_ASCII));
	memcpy(cfebuf_g + strlen(NVRAM_MAGIC_ASCII), cfebuf, CFEBUF_LEN - strlen(NVRAM_MAGIC_ASCII));

	file_unlock(lock);

	if (fp) fclose(fp);

	return 0;
#endif
}

