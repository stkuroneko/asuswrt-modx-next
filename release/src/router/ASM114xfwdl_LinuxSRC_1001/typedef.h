#ifndef	_COMMON_H_
#define	_COMMON_H_

typedef unsigned long DWORD;
typedef unsigned short WORD;
typedef unsigned char BYTE;
typedef DWORD *PDWORD;
typedef WORD *PWORD;
typedef BYTE *PBYTE;


typedef int INT;
typedef int *PINT;
typedef unsigned int UINT;
typedef unsigned int *PUINT;
typedef void VOID;
typedef float FLOAT;
typedef float *PFLOAT;

typedef int BOOL;
#define	TRUE    1
#define	FALSE   0

#define	NONE    -1


#endif  /* _COMMON_H_ */

